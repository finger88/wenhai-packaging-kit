def photo_pool() -> list[Path]:
    """29 张唯一现场照片（按文件名去重后的实际路径）。"""
    seen: dict[str, Path] = {}
    for p in sorted((STAGING / "uploads" / "projects").rglob("ID_*.jpeg")):
        seen.setdefault(p.name, p)
    return [seen[k] for k in sorted(seen)]

def assign_photos() -> dict[tuple[str, str], list[Path]]:
    """确定性分配：每条核查 3~8 张；Q1/Q2 使用池的不同区段，避免同期完全重复。"""
    rng = random.Random(20260918)
    pool = photo_pool()
    rng.shuffle(pool)
    result: dict[tuple[str, str], list[Path]] = {}
    idx = 0
    ordered = sorted(_INS_NOTES.keys())
    for key in ordered:
        n = rng.randint(3, min(8, len(pool)))
        photos = []
        for _ in range(n):
            photos.append(pool[idx % len(pool)])
            idx += 1
        result[key] = photos
    return result

